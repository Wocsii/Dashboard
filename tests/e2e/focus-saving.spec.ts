import { expect, test } from '@playwright/test'

test('guarda el enfoque sin hábito al pausar y reanudar sin duplicar sesiones', async ({ page }) => {
  await page.goto('/enfoque')
  await page.getByRole('button', { name: 'Empezar', exact: true }).waitFor()
  await page.clock.install()
  await page.getByRole('button', { name: 'Empezar', exact: true }).click()
  await page.clock.fastForward(65_000)
  await page.getByRole('button', { name: 'Pausar', exact: true }).click()
  await expect.poll(async () => page.evaluate(() => {
    const data = JSON.parse(localStorage.getItem('mi-espacio:demo-data:v1') ?? '{}')
    return data.focusSessions?.filter((s: { started_at: string }) => Date.parse(s.started_at) > Date.now() - 70_000).map((s: { duration_seconds: number }) => s.duration_seconds)
  })).toEqual([65])
  await expect(page.getByText('Tiempo guardado', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await page.clock.fastForward(60_000)
  await page.getByRole('button', { name: 'Pausar', exact: true }).click()
  await expect.poll(async () => page.evaluate(() => {
    const data = JSON.parse(localStorage.getItem('mi-espacio:demo-data:v1') ?? '{}')
    return data.focusSessions?.filter((s: { started_at: string }) => Date.parse(s.started_at) > Date.now() - 130_000).map((s: { duration_seconds: number }) => s.duration_seconds)
  })).toEqual([125])
  await page.reload()
  await expect(page.getByRole('button', { name: 'Continuar', exact: true })).toBeVisible()
})

test('añade enfoque y descanso manualmente sin arrancar el reloj', async ({ page }) => {
  await page.goto('/enfoque')
  await page.getByLabel('Minutos a añadir').fill('40')
  await page.getByRole('button', { name: 'Añadir minutos', exact: true }).click()
  await expect(page.getByText('Minutos añadidos', { exact: true })).toBeVisible()
  await page.getByLabel('Tipo de tiempo').selectOption('short_break')
  await page.getByLabel('Minutos a añadir').fill('10')
  await page.getByRole('button', { name: 'Añadir minutos', exact: true }).click()
  await expect(page.getByText('Minutos añadidos', { exact: true })).toBeVisible()
  const manual = await page.evaluate(() => JSON.parse(localStorage.getItem('mi-espacio:demo-data:v1')!).focusSessions.filter((s: { completed: boolean; task_id: string | null }) => !s.completed && !s.task_id).map((s: { kind: string; duration_seconds: number }) => [s.kind, s.duration_seconds]))
  expect(manual).toContainEqual(['focus', 2400])
  expect(manual).toContainEqual(['short_break', 600])
  await expect(page.getByRole('button', { name: 'Empezar', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Editar duración del enfoque' })).toHaveText('25:00')
})

test('edita la duración desde el centro y conserva el tramo de enfoque anterior', async ({ page }) => {
  await page.goto('/enfoque')
  await page.getByRole('button', { name: 'Editar duración del enfoque' }).click()
  await page.getByRole('spinbutton', { name: 'Duración del enfoque en minutos' }).fill('30')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Editar duración del enfoque' })).toHaveText('30:00')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Editar duración del enfoque' })).toHaveText('30:00')
  await page.clock.install()
  await page.getByRole('button', { name: 'Empezar', exact: true }).click()
  await page.clock.fastForward(65_000)
  await page.getByRole('button', { name: 'Editar duración del enfoque' }).click()
  await page.getByRole('spinbutton', { name: 'Duración del enfoque en minutos' }).fill('40')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Editar duración del enfoque' })).toHaveText('40:00')
  await expect(page.getByRole('button', { name: 'Pausar', exact: true })).toBeVisible()
  await expect.poll(async () => page.evaluate(() => JSON.parse(localStorage.getItem('mi-espacio:demo-data:v1')!).focusSessions.some((s: { completed: boolean; duration_seconds: number }) => !s.completed && s.duration_seconds === 65))).toBe(true)
})

test('el botón redondo amarillo inicia y reanuda un cronómetro indefinido sin tarea', async ({ page }) => {
  await page.goto('/enfoque')
  const start = page.getByRole('button', { name: 'Iniciar cronómetro indefinido', exact: true })
  await expect(start).toHaveClass(/bg-sun/)
  await expect(start).toHaveClass(/rounded-full/)
  await page.clock.install()
  await start.click()
  await expect(page.getByText('Enfoque sin límite · Tiempo transcurrido')).toBeVisible()
  await page.clock.fastForward(120_000)
  await page.getByRole('button', { name: 'Pausar', exact: true }).click()
  await expect(page.getByText(/^02:0\d$/)).toBeVisible()
  await page.getByRole('button', { name: 'Continuar cronómetro indefinido', exact: true }).click()
  await page.clock.fastForward(60_000)
  await page.getByRole('button', { name: 'Pausar', exact: true }).click()
  await expect(page.getByText(/^03:0\d$/)).toBeVisible()
})
