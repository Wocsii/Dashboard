import { expect, test } from '@playwright/test'

for (const path of ['/tareas', '/kanban']) {
  test(`enfoque desde ${path}: aparece al pasar el cursor y continúa sin límite`, async ({ page }) => {
    await page.goto(path)
    await page.evaluate(() => localStorage.clear())
    await page.reload()
    const title = 'Llamar al dentista'
    const button = page.getByRole('button', { name:`Activar enfoque indefinido: ${title}`,exact:true })
    await expect(button).toHaveCSS('opacity','0')
    await page.getByText(title, { exact:true }).hover()
    await expect(button).toHaveCSS('opacity','1')
    await button.click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('button', { name:`Detener enfoque: ${title}` })).toHaveAttribute('aria-pressed','true')
    await page.reload()
    await expect(page.getByRole('button', { name:`Detener enfoque: ${title}` })).toHaveAttribute('aria-pressed','true')
    await page.clock.install()
    await page.clock.fastForward(26 * 60_000)
    await page.getByRole('link', { name:'Enfoque',exact:true }).click()
    await expect(page.getByText('Enfoque sin límite · Tiempo transcurrido')).toBeVisible()
    await expect(page.getByText(/^26:0\d$/)).toBeVisible()
    await expect(page.getByRole('combobox', { name:'Tarea en la que te concentras' })).toHaveValue('t6')
    await page.getByRole('button', { name:'Finalizar enfoque',exact:true }).click()
    await expect(page.getByRole('button', { name:'Empezar',exact:true })).toBeVisible()
  })
}

test('Inicio conserva la píldora compacta y continúa el cronómetro de Enfoque', async ({ page }) => {
  await page.goto('/')
  const start = page.getByRole('button', { name: 'Iniciar cronómetro indefinido', exact: true })
  await expect(start).toBeVisible()
  const size = await start.boundingBox()
  expect(size!.height).toBe(52)
  await expect(start.locator('span').last()).toHaveCSS('white-space', 'nowrap')
  const inactiveColor = await start.locator('span').first().evaluate(element => getComputedStyle(element).backgroundColor)
  await start.click()
  const pause = page.getByRole('button', { name: 'Pausar cronómetro indefinido', exact: true })
  await expect(pause.locator('span').first()).not.toHaveCSS('background-color', inactiveColor)
  await pause.click()
  await expect(page.getByRole('button', { name: 'Continuar cronómetro indefinido', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Continuar cronómetro indefinido', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pausar cronómetro indefinido' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('link', { name: 'Enfoque', exact: true }).click()
  await expect(page.getByText('Enfoque sin límite · Tiempo transcurrido')).toBeVisible()
  await page.getByRole('button', { name: 'Pausar', exact: true }).click()
  await page.getByRole('link', { name: 'Inicio', exact: true }).click()
  const resume = page.getByRole('button', { name: 'Continuar cronómetro indefinido', exact: true })
  await expect(resume).toBeVisible()
  await page.screenshot({ path: '/tmp/dashboard-indefinite.png', fullPage: true })
  await resume.click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Pausar cronómetro indefinido' })).toHaveAttribute('aria-pressed', 'true')
})

test('al salir de Enfoque limpia la tarea y conserva el reloj sin duplicar tiempo', async ({ page }) => {
  await page.goto('/enfoque')
  await page.getByRole('combobox', { name: 'Tarea en la que te concentras' }).selectOption('t6')
  await page.clock.install()
  await page.getByRole('button', { name: 'Iniciar cronómetro indefinido', exact: true }).click()
  const started = await page.evaluate(() => JSON.parse(localStorage.getItem('mi-espacio:pomodoro:v1')!))
  expect(started.taskId).toBe('t6')
  await page.clock.fastForward(3000)
  await page.getByRole('link', { name: 'Inicio', exact: true }).click()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('mi-espacio:pomodoro:v1')!).taskId)).toBeNull()
  const detached = await page.evaluate(() => JSON.parse(localStorage.getItem('mi-espacio:pomodoro:v1')!))
  expect(detached.state.startedAt).toBe(started.state.startedAt)
  expect(detached.state.status).toBe('running')
  await page.clock.fastForward(2000)
  await page.getByRole('button', { name: 'Pausar cronómetro indefinido', exact: true }).click()
  await expect.poll(() => page.evaluate(start => {
    const rows = JSON.parse(localStorage.getItem('mi-espacio:demo-data:v1')!).focusSessions.filter((row: { started_at: string }) => Date.parse(row.started_at) >= start)
    return { total: rows.reduce((sum: number, row: { duration_seconds: number }) => sum + row.duration_seconds, 0), linked: rows.some((row: { task_id: string | null }) => row.task_id === 't6'), unassigned: rows.some((row: { task_id: string | null }) => row.task_id === null) }
  }, started.state.startedAt)).toEqual({ total: 5, linked: true, unassigned: true })
  await page.getByRole('link', { name: 'Enfoque', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Tarea en la que te concentras' })).toHaveValue('')
})

test('una selección sin iniciar tampoco se conserva al salir de Enfoque', async ({ page }) => {
  await page.goto('/enfoque')
  const select = page.getByRole('combobox', { name: 'Tarea en la que te concentras' })
  await select.selectOption('t6')
  await page.getByRole('link', { name: 'Inicio', exact: true }).click()
  await page.getByRole('link', { name: 'Enfoque', exact: true }).click()
  await expect(select).toHaveValue('')
  await select.selectOption('t6')
  await page.reload()
  await expect(select).toHaveValue('')
})
