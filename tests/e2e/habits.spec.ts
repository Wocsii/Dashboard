import { expect, test } from '@playwright/test'

test('hábitos: creación, reloj, registro único y corrección diaria', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Mis hábitos' })).toHaveCount(0)
  await page.goto('/proyectos')
  await page.getByRole('button', { name: 'Nuevo proyecto o hábito' }).click()
  await page.getByRole('switch', { name: 'Crear como hábito' }).check()
  await page.getByRole('textbox', { name: 'Nombre', exact: true }).fill('Estudiar japonés')
  await page.getByRole('button', { name: 'Crear hábito', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Mis hábitos' })).toBeVisible()
  await expect(page.getByLabel('Semana de Estudiar japonés')).toHaveCount(0)
  await page.getByRole('button', { name: 'Iniciar reloj', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Hecho hoy', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Pausar', exact: true }).click()
  await page.getByRole('button', { name: 'Iniciar reloj', exact: true }).click()
  await expect.poll(async () => page.evaluate(() => {
    const data = JSON.parse(localStorage.getItem('mi-espacio:demo-data:v1')!)
    return data.exerciseLogs.length
  })).toBe(1)
  await page.getByRole('button', { name: 'Pausar', exact: true }).click()
  await page.getByRole('button', { name: 'Hecho hoy', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Marcar hoy', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Marcar hoy', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Detener enfoque: Estudiar japonés', exact: true }).click()
  await page.getByRole('button', { name: 'Activar enfoque indefinido: Estudiar japonés', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Hecho hoy', exact: true })).toBeVisible()
  await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'night'))
  await page.waitForTimeout(500)
  await page.screenshot({ path: '/tmp/habits-night.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('heading', { name: 'Mis hábitos' }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: '/tmp/habits-mobile.png', fullPage: true })
  await page.goto('/proyectos')
  await expect(page.getByLabel('Semana de Estudiar japonés')).toBeVisible()
  await page.getByRole('button', { name: 'Estudiar japonés', exact: true }).click()
  await page.getByRole('button', { name: 'Editar proyecto', exact: true }).click()
  await page.getByRole('dialog').getByRole('radio', { name: 'Pausado', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Mis hábitos' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Tareas de hábitos' })).toHaveCount(0)
  await page.evaluate(() => {
    const key = 'mi-espacio:demo-data:v1'
    const data = JSON.parse(localStorage.getItem(key)!)
    const habit = data.projects.find((p: { name: string }) => p.name === 'Estudiar japonés')
    habit.status = 'active'
    data.projects.push({ ...habit, id: crypto.randomUUID(), name: 'Gimnasio', color: 'mint' })
    localStorage.setItem(key, JSON.stringify(data))
  })
  await page.reload()
  const habits = page.getByRole('region', { name: 'Mis hábitos', exact: true })
  await expect(habits.getByRole('link')).toHaveCount(2)
  await expect(page.getByRole('heading', { name: 'Proyectos activos', exact: true })).toHaveCount(0)
  await habits.scrollIntoViewIfNeeded()
  await page.screenshot({ path: '/tmp/habits-squares-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 900 })
  await habits.scrollIntoViewIfNeeded()
  await page.screenshot({ path: '/tmp/habits-squares-desktop.png', fullPage: true })

})
