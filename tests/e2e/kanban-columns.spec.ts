import { expect, test } from '@playwright/test'

test('sin Google Tasks: crear columna y tarjeta, mover con teclado y conservar tras recargar', async ({ page }) => {
  await page.goto('/kanban')
  await page.getByRole('button', { name: 'Añadir columna', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nombre de la columna').fill('En revisión')
  await dialog.getByRole('button', { name: 'Crear columna', exact: true }).click()
  const custom = page.getByRole('region', { name: /En revisión/ })
  await expect(custom).toBeVisible()
  await custom.getByRole('button', { name: 'Añadir en En revisión' }).click()
  await dialog.getByLabel('Título', { exact: true }).fill('Revisar borrador')
  await dialog.getByRole('button', { name: 'Crear tarea', exact: true }).click()
  await expect(custom.getByText('Revisar borrador')).toBeVisible()
  await page.reload()
  await expect(custom.getByText('Revisar borrador')).toBeVisible()
  const card = page.getByRole('button', { name: /^Comparar vuelos/ })
  await card.focus()
  await page.keyboard.press('Space')
  await page.waitForTimeout(150)
  await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(200)
  await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(200)
  await page.keyboard.press('Space')
  await expect(custom.getByText('Comparar vuelos')).toBeVisible()
  await page.reload()
  await expect(custom.getByText('Comparar vuelos')).toBeVisible()
})
