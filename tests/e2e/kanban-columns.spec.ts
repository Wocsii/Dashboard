import { expect, test } from '@playwright/test'

test('sin Google Tasks: crear columna y tarjeta, mover con teclado y conservar tras recargar', async ({ page }) => {
  await page.goto('/kanban')
  await page.getByRole('button', { name: 'Añadir columna', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nombre de la columna').fill('En revisión')
  await dialog.locator('label[title="Lila"]').click()
  await expect(dialog.getByRole('radio', { name: 'Lila', exact: true })).toBeChecked()
  await dialog.getByRole('button', { name: 'Crear columna', exact: true }).click()
  const custom = page.getByRole('region', { name: /En revisión/ })
  await expect(custom).toBeVisible()
  await expect(custom.locator('h2 > span[aria-hidden]')).toHaveAttribute('style', /--project-lilac/)
  await custom.getByRole('button', { name: 'Añadir en En revisión' }).click()
  await dialog.getByLabel('Título', { exact: true }).fill('Revisar borrador')
  await dialog.getByRole('button', { name: 'Crear tarea', exact: true }).click()
  await expect(custom.getByText('Revisar borrador')).toBeVisible()
  await page.reload()
  await expect(custom.locator('h2 > span[aria-hidden]')).toHaveAttribute('style', /--project-lilac/)
  await expect(custom.getByText('Revisar borrador')).toBeVisible()
  const card = page.getByRole('button', { name: /^Comparar vuelos/ })
  await card.focus()
  await page.keyboard.press('Space')
  await page.waitForTimeout(150)
  await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(200)
  await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(200)
  await page.keyboard.press('Space')
  await expect(custom.getByText('Comparar vuelos')).toBeVisible()
  await page.reload()
  await expect(custom.getByText('Comparar vuelos')).toBeVisible()
})

test('elige columnas en ajustes y limita la creación a seis', async ({ page }) => {
  await page.goto('/kanban')
  for (const title of ['Revisión', 'Más adelante']) {
    await page.getByRole('button', { name: 'Añadir columna', exact: true }).click()
    await page.getByLabel('Nombre de la columna').fill(title)
    await page.getByRole('button', { name: 'Crear columna', exact: true }).click()
  }
  await expect(page.getByRole('button', { name: 'Añadir columna', exact: true })).toBeDisabled()
  await expect(page.getByRole('region')).toHaveCount(6)
  await page.getByRole('link', { name: 'Ajustes', exact: true }).first().click()
  await page.locator('summary').filter({ hasText: 'Columnas del tablero' }).click()
  await page.getByRole('checkbox', { name: 'Revisión', exact: true }).uncheck()
  await page.getByRole('link', { name: 'Tablero', exact: true }).click()
  await expect(page.getByRole('region')).toHaveCount(5)
  await expect(page.getByRole('region', { name: /Revisión/ })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('region')).toHaveCount(5)
  await page.getByRole('link', { name: 'Ajustes', exact: true }).first().click()
  await page.locator('summary').filter({ hasText: 'Columnas del tablero' }).click()
  await page.getByRole('checkbox', { name: 'Revisión', exact: true }).check()
  await page.getByRole('link', { name: 'Tablero', exact: true }).click()
  await expect(page.getByRole('region')).toHaveCount(6)
})


test('reordena columnas y borra desde ajustes conservando las tareas', async ({ page }) => {
  await page.goto('/kanban')
  const handle = page.getByRole('button', { name: 'Mover columna Pendiente', exact: true })
  await handle.focus()
  await page.keyboard.press('Space')
  await page.waitForTimeout(150)
  await page.keyboard.press('ArrowRight')
  await page.waitForTimeout(250)
  await page.keyboard.press('Space')
  await expect(page.getByRole('region').first()).toHaveAccessibleName(/En progreso/)
  await page.reload()
  await expect(page.getByRole('region').first()).toHaveAccessibleName(/En progreso/)
  await page.getByRole('link', { name: 'Ajustes', exact: true }).first().click()
  await page.locator('summary').filter({ hasText: 'Columnas del tablero' }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Eliminar columna Bloqueada', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: 'Bloqueada', exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Tablero', exact: true }).click()
  await expect(page.getByRole('region', { name: /Bloqueada/ })).toHaveCount(0)
  await expect(page.getByText('Comparar vuelos')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Comparar vuelos')).toBeVisible()
  await expect(page.getByRole('region')).toHaveCount(3)
})

test('arrastra columnas con ratón y conserva el orden', async ({ page }) => {
  await page.goto('/kanban')
  const sourceHandle = page.getByRole('button', { name: 'Mover columna Pendiente', exact: true })
  await expect(sourceHandle).toHaveCSS('opacity', '0')
  await sourceHandle.hover()
  await expect(sourceHandle).toHaveCSS('opacity', '1')
  await page.mouse.move(1000, 10)
  await expect(sourceHandle).toHaveCSS('opacity', '0')
  await sourceHandle.focus()
  await expect(sourceHandle).toHaveCSS('opacity', '1')
  await sourceHandle.evaluate(element => element.blur())
  const source = await sourceHandle.boundingBox()
  const target = await page.getByRole('button', { name: 'Mover columna En progreso', exact: true }).boundingBox()
  if (!source || !target) throw new Error('Faltan las asas de las columnas')
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2)
  await page.mouse.down()
  await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 12 })
  await page.mouse.up()
  await expect(page.getByRole('region').first()).toHaveAccessibleName(/En progreso/)
  await page.reload()
  await expect(page.getByRole('region').first()).toHaveAccessibleName(/En progreso/)
})

