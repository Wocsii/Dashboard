import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/proyectos')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
})

test('proyecto de ejercicio: frecuencia, métricas, registro diario y persistencia', async ({ page }) => {
  await page.getByRole('button', { name:'Nuevo proyecto',exact:true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nombre', { exact:true }).fill('Completar 10k')
  await dialog.getByRole('switch', { name:'Proyecto de ejercicio' }).check()
  await dialog.getByLabel('Entrenamientos por semana').fill('4')
  await dialog.getByRole('checkbox', { name:'Distancia (km)',exact:true }).check()
  await dialog.getByLabel('Meta de distancia').fill('10')
  await dialog.getByRole('checkbox', { name:'Intensidad (/10)',exact:true }).uncheck()
  await dialog.getByRole('button', { name:'Crear proyecto',exact:true }).click()
  await expect(dialog).not.toBeVisible()
  const card = page.getByRole('article').filter({ has:page.getByRole('heading', { name:'Completar 10k',exact:true }) })
  await expect(card).toContainText('0/4')
  await card.getByRole('button').click()
  const details = page.getByRole('complementary', { name:'Detalle del proyecto' })
  await expect(details.getByText('Meta: 10 km', { exact:true })).toBeVisible()
  await details.getByRole('button', { name:'Hoy entrené',exact:true }).click()
  await expect(card).toContainText('1/4')
  await details.getByRole('button', { name:'Hoy entrené',exact:true }).click()
  await expect(card).toContainText('1/4')
  await details.getByLabel('Tiempo (min)', { exact:true }).fill('35')
  await details.getByLabel('Distancia (km)', { exact:true }).fill('5.2')
  await details.getByRole('button', { name:'Guardar entrenamiento',exact:true }).click()
  await expect(details.getByRole('table', { name:'Distancia de Completar 10k' })).toContainText('5.2 km')
  await page.screenshot({ path:'/tmp/dashboard-exercise-desktop.png',fullPage:true })
  await page.reload()
  await card.getByRole('button').click()
  await expect(details.getByLabel('Distancia (km)', { exact:true })).toHaveValue('5.2')
  await details.getByRole('button', { name:'Hoy descansé',exact:true }).click()
  await expect(card).toContainText('0/4')
  await expect(details.getByRole('button', { name:'Hoy descansé',exact:true })).toHaveAttribute('aria-pressed','true')
  await details.getByRole('button', { name:'Editar proyecto',exact:true }).click()
  await expect(dialog.getByLabel('Entrenamientos por semana')).toHaveValue('4')
  await expect(dialog.getByLabel('Meta de distancia')).toHaveValue('10')
  await dialog.getByRole('checkbox', { name:'Peso (kg)',exact:true }).check()
  await dialog.getByRole('button', { name:'Guardar',exact:true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(details.getByLabel('Peso (kg)', { exact:true })).toBeVisible()
  await page.setViewportSize({ width:390,height:844 })
  await details.getByLabel('Día del registro', { exact:true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path:'/tmp/dashboard-exercise-mobile.png',fullPage:true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(await page.locator('#contenido').evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
})

test('los proyectos normales y de ejercicio comparten cuadrícula y tamaño', async ({ page }) => {
  for (const exercise of [false,true]) {
    await page.getByRole('button', { name:'Nuevo proyecto',exact:true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Nombre', { exact:true }).fill(exercise ? 'Fuerza semanal' : 'Proyecto normal')
    if (exercise) await dialog.getByRole('switch', { name:'Proyecto de ejercicio' }).check()
    await dialog.getByRole('button', { name:'Crear proyecto',exact:true }).click()
    await expect(dialog).not.toBeVisible()
  }
  const normal = page.getByRole('article').filter({ has:page.getByRole('heading', { name:'Proyecto normal',exact:true }) })
  const exercise = page.getByRole('article').filter({ has:page.getByRole('heading', { name:'Fuerza semanal',exact:true }) })
  const a = (await normal.boundingBox())!, b = (await exercise.boundingBox())!
  expect(Math.abs(a.width - b.width)).toBeLessThan(2)
  expect(Math.abs(a.height - b.height)).toBeLessThan(2)
  await normal.getByRole('button').click()
  await expect(page.getByLabel('Progreso de ejercicio')).toHaveCount(0)
  await exercise.getByRole('button').click()
  await expect(page.getByLabel('Progreso de ejercicio')).toBeVisible()
})
