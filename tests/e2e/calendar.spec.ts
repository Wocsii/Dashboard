test('el cuaderno hace zoom con la rueda del ratón y con el pellizco de dos dedos', async ({ page }) => {
  await page.goto('/notas')
  await page.getByRole('button', { name: 'Nuevo cuaderno', exact: true }).click()
  await page.getByLabel('¿Qué nombre quieres ponerle?').fill('Cuaderno de zoom')
  await page.getByRole('button', { name: 'Crear cuaderno', exact: true }).click()
  const surface = page.getByRole('region', { name: 'Superficie del cuaderno' })
  const world = page.locator('.kw-world')
  const scale = async () => world.evaluate((node) => new DOMMatrix(getComputedStyle(node).transform).a)
  const start = await scale()
  const box = await surface.boundingBox()
  if (!box) throw new Error('No surface')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.wheel(0, -300)
  await expect.poll(scale).toBeGreaterThan(start)
  const zoomed = await scale()
  await page.mouse.wheel(0, 300)
  await expect.poll(scale).toBeLessThan(zoomed)
  const before = await scale()
  await surface.evaluate((node, [cx, cy]) => {
    const fire = (type: string, id: number, x: number, y: number) => node.dispatchEvent(new PointerEvent(type, { bubbles: true, pointerId: id, pointerType: 'touch', button: 0, clientX: x, clientY: y }))
    fire('pointerdown', 11, cx - 40, cy); fire('pointerdown', 12, cx + 40, cy)
    fire('pointermove', 11, cx - 100, cy); fire('pointermove', 12, cx + 100, cy)
    fire('pointerup', 11, cx - 100, cy); fire('pointerup', 12, cx + 100, cy)
  }, [box.x + box.width / 2, box.y + box.height / 2])
  await expect.poll(scale).toBeGreaterThan(before * 1.5)
  await expect(page.locator('.kw-element-drawing')).toHaveCount(0)
})
