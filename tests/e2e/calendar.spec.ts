test('arrastrar un bloque guarda el nuevo horario sin cambiar su duración', async ({ page }) => {
  await page.getByRole('button', { name: 'Nuevo evento', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Título del evento').fill('Plan para mover')
  await dialog.getByRole('button', { name: 'Añadir evento' }).click()
  const event = page.getByRole('button', { name: /^Plan para mover, / })
  await expect(event).toBeVisible()
  const tile = page.locator('[data-calendar-event]').filter({ has: event })
  const target = page.locator('button[aria-label^="Crear evento"][aria-label$="10:00"]').first()
  await tile.dragTo(target)
  await expect(event).toHaveAccessibleName(/10:00–11:00/)
  await page.reload()
  await expect(event).toHaveAccessibleName(/10:00–11:00/)
})

