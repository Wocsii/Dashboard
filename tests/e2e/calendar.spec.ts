import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.goto('/calendario/visual')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
})

test('la agenda llega al borde inferior y permite recorrer las 24 horas', async ({ page }) => {
  for (const viewport of [{ width:1440,height:900 }, { width:1440,height:720 }, { width:390,height:844 }]) {
    await page.setViewportSize(viewport)
    const agenda = page.getByLabel('Agenda semanal')
    await expect(agenda).toBeVisible()
    const region = page.getByRole('region', { name:'Calendario de Google' })
    await expect.poll(async () => {
      const board = await agenda.boundingBox(), container = await region.boundingBox()
      return board && container ? Math.abs(board.y + board.height - container.y - container.height) : 100
    }).toBeLessThan(2)
    await agenda.evaluate((element) => { element.scrollTop = element.scrollHeight })
    await expect(agenda.getByText('23:00', { exact:true })).toBeVisible()
    expect(await agenda.evaluate((element) => element.scrollHeight > element.clientHeight)).toBe(true)
  }
})

test('calendario: crear, editar duración, filtrar y borrar un evento', async ({ page }) => {
  await page.getByRole('button', { name: 'Nuevo evento', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Título del evento').fill('Mi plan de prueba')
  await dialog.getByLabel('Lugar', { exact: true }).fill('Biblioteca')
  await dialog.getByLabel('Categoría').selectOption('Trabajo')
  await dialog.getByLabel('Color', { exact: true }).selectOption('3')
  await dialog.getByRole('button', { name: 'Añadir evento' }).click()
  const event = page.getByRole('button', { name: /^Mi plan de prueba, / })
  await expect(event).toBeVisible()
  await page.reload()
  await expect(event).toBeVisible()
  await page.screenshot({ path: '/tmp/calendar-desktop.png', animations: 'disabled' })
  const resize = page.getByRole('button', { name: 'Cambiar duración de Mi plan de prueba' })
  await resize.focus()
  await resize.press('ArrowDown')
  await expect(event).toHaveAccessibleName(/10:15/)
  await event.click()
  await expect(dialog.getByLabel('Lugar', { exact: true })).toHaveValue('Biblioteca')
  await dialog.getByLabel('Título del evento').fill('Mi plan actualizado')
  await page.screenshot({ path: '/tmp/calendar-dialog.png', animations: 'disabled' })
  await dialog.getByRole('button', { name: 'Guardar cambios' }).click()
  const updated = page.getByRole('button', { name: /^Mi plan actualizado, / })
  await expect(updated).toBeVisible()
  await page.getByRole('checkbox', { name: 'Personal', exact: true }).uncheck()
  await expect(updated).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Personal', exact: true }).check()
  await expect(updated).toBeVisible()
  await updated.click()
  await dialog.getByRole('button', { name: 'Eliminar', exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirmar eliminación' }).click()
  await expect(updated).toHaveCount(0)
})

