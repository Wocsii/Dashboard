test('Pencil bloquea desplazamiento y los toques de la palma no dibujan', async ({ page }) => {
  await page.getByRole('button', { name: 'Escribir y decorar esta semana' }).click()
  await page.getByRole('button', { name: 'Modo iPad', exact: true }).click()
  await page.getByRole('button', { name: 'Escribir a mano', exact: true }).click()
  const paper = page.getByRole('region', { name: 'Superficie del cuaderno' })
  await expect(paper).toHaveCSS('touch-action', 'none')
  const before = await page.evaluate(() => ({ x: window.scrollX, y: window.scrollY }))
  await paper.evaluate((node) => {
    for (const type of ['pointerdown', 'pointermove', 'pointerup']) node.dispatchEvent(new PointerEvent(type, { bubbles: true, pointerId: 90, pointerType: 'touch', button: 0, clientX: 200, clientY: 200 }))
  })
  await expect(page.locator('.kw-element-drawing')).toHaveCount(0)
  const bounds = await paper.boundingBox()
  if (!bounds) throw new Error('No paper')
  await page.mouse.move(bounds.x + 100, bounds.y + 100)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 200, bounds.y + 150, { steps: 10 })
  await page.mouse.up()
  await expect(page.locator('.kw-element-drawing')).toHaveCount(1)
  expect(await page.evaluate(() => ({ x: window.scrollX, y: window.scrollY }))).toEqual(before)
  await expect(page.getByText('Guardado', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.kw-element-drawing')).toHaveCount(1)
})
