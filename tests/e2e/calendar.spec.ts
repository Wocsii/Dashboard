test('Pencil bloquea desplazamiento y los toques de la palma no dibujan', async ({ page }) => {
  await page.getByRole('button', { name: 'Escribir y decorar esta semana' }).click()
  await page.getByRole('button', { name: 'Modo iPad', exact: true }).click()
  await page.getByRole('button', { name: 'Escribir a mano', exact: true }).click()
  const paper = page.getByRole('region', { name: 'Superficie del cuaderno' })
  await expect(paper).toHaveCSS('touch-action', 'none')
  const before = await page.evaluate(() => ({ x: window.scrollX, y: window.scrollY }))
  await paper.evaluate((node) => {
    for (const type of ['pointerdown', 'pointermove', 'pointerup']) node.dispatchEvent(new PointerEvent(type, { bubbles: true, pointerId: 90, pointerType: 'touch', button: 0, clientX: 200, clientY: 200 }))
  })
  await expect(page.locator('.kw-element-drawing')).toHaveCount(0)
  const bounds = await paper.boundingBox()
  if (!bounds) throw new Error('No paper')
  await page.mouse.move(bounds.x + 100, bounds.y + 100)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 200, bounds.y + 150, { steps: 10 })
  await page.mouse.up()
  await expect(page.locator('.kw-element-drawing')).toHaveCount(1)
  expect(await page.evaluate(() => ({ x: window.scrollX, y: window.scrollY }))).toEqual(before)
  await expect(page.getByText('Guardado', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('.kw-element-drawing')).toHaveCount(1)
})

test('el arrastre rápido usa la posición al soltar y no retrocede al perder captura', async ({ page }) => {
  await page.goto('/notas')
  await page.getByRole('button', { name: 'Nuevo cuaderno', exact: true }).click()
  await page.getByRole('button', { name: 'Abrir stickers' }).click()
  await page.getByRole('button', { name: 'Añadir Osito rosa', exact: true }).click()
  await page.getByRole('button', { name: 'Cerrar stickers' }).click()
  const paper = page.getByRole('region', { name: 'Superficie del cuaderno' })
  const sticker = page.getByRole('group', { name: 'Sticker 1' })
  await paper.evaluate((node) => node.addEventListener('pointerdown', (event) => { node.dataset.testPointer = String((event as PointerEvent).pointerId) }))
  const before = await sticker.evaluate((node) => ({ x: parseFloat(node.style.left), y: parseFloat(node.style.top) }))
  const zoom = await page.locator('.kw-world').evaluate((node) => new DOMMatrix(getComputedStyle(node).transform).a)
  const box = await sticker.boundingBox()
  if (!box) throw new Error('Sticker no visible')
  const x = box.x + box.width / 2, y = box.y + box.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 40, y + 15, { steps: 1 })
  // Deliver a release farther away than the last move, as with a very fast drag.
  await paper.evaluate((node, point) => node.dispatchEvent(new PointerEvent('pointerup', { bubbles: true, pointerId: Number(node.dataset.testPointer), pointerType: 'mouse', button: 0, clientX: point.x, clientY: point.y })), { x: x + 120, y: y + 60 })
  await page.mouse.up()
  const released = await sticker.evaluate((node) => ({ x: parseFloat(node.style.left), y: parseFloat(node.style.top) }))
  expect(released.x).toBeCloseTo(before.x + 120 / zoom, 0)
  expect(released.y).toBeCloseTo(before.y + 60 / zoom, 0)
  const movedBox = await sticker.boundingBox()
  if (!movedBox) throw new Error('Sticker no visible')
  await page.mouse.move(movedBox.x + movedBox.width / 2, movedBox.y + movedBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(movedBox.x + movedBox.width / 2 + 45, movedBox.y + movedBox.height / 2 + 20, { steps: 1 })
  const moved = await sticker.evaluate((node) => ({ x: node.style.left, y: node.style.top }))
  await paper.evaluate((node) => node.dispatchEvent(new PointerEvent('lostpointercapture', { bubbles: true, pointerId: Number(node.dataset.testPointer), pointerType: 'mouse' })))
  await page.mouse.up()
  await expect(sticker).toHaveCSS('left', moved.x)
  await expect(sticker).toHaveCSS('top', moved.y)
  await expect(page.getByText('Guardado', { exact: true })).toBeVisible()
  await page.reload()
  await expect(sticker).toHaveCSS('left', moved.x)
  await expect(sticker).toHaveCSS('top', moved.y)
})

test('Retroceso y Suprimir borran la selección sin borrar objetos al editar texto', async ({ page }) => {
  await page.goto('/notas')
  await page.getByRole('button', { name: 'Nuevo cuaderno', exact: true }).click()
  await page.getByRole('button', { name: 'Abrir stickers' }).click()
  await page.getByRole('button', { name: 'Añadir Osito rosa', exact: true }).click()
  await page.getByRole('button', { name: 'Cerrar stickers' }).click()
  const sticker = page.getByRole('group', { name: 'Sticker 1' })
  await sticker.click()
  await page.keyboard.press('Backspace')
  await expect(sticker).toHaveCount(0)
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  await expect(sticker).toBeVisible()
  await page.getByRole('button', { name: 'Girar elemento', exact: true }).click()
  await page.keyboard.press('Delete')
  await expect(sticker).toHaveCount(0)
  await page.getByRole('button', { name: 'Añadir texto manuscrito', exact: true }).click()
  const text = page.getByLabel('Texto manuscrito', { exact: true })
  await text.fill('hola')
  await text.press('Backspace')
  await expect(text).toHaveValue('hol')
  await expect(page.getByRole('group', { name: 'Texto 1' })).toHaveCount(1)
  const title = page.getByLabel('Título de la pizarra')
  await title.fill('Cuaderno')
  await title.press('Backspace')
  await expect(title).toHaveValue('Cuadern')
  await expect(text).toHaveValue('hol')
})
