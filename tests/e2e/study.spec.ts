import { expect, test } from '@playwright/test'

test('estudio: formulario, meta obligatoria, pausa y tiempo excluido del enfoque', async ({ page }) => {
  await page.goto('/proyectos')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.getByRole('button', { name:'Nuevo proyecto o hábito' }).click()
  await page.getByRole('switch', { name:'Crear como hábito' }).check()
  await page.getByLabel('Tipo de hábito', { exact:true }).selectOption('study')
  await page.getByLabel('Nombre', { exact:true }).fill('Estudio de matemáticas')
  await page.getByRole('radiogroup', { name:'Contabilizar como enfoque' }).getByRole('radio', { name:'No',exact:true }).click()
  await page.getByLabel('Establecer una meta diaria de tiempo').check()
  await page.getByLabel('Meta diaria', { exact:true }).fill('1')
  await page.getByLabel('Exigir la meta para completar el día').check()
  await page.getByLabel('Unidad de trabajo', { exact:true }).selectOption('ejercicios')
  await expect(page.getByText(/concentración|intensidad/i)).toHaveCount(0)
  await page.getByRole('dialog').screenshot({path:'/tmp/study-dialog.png'})
  await page.getByRole('button', { name:'Crear hábito',exact:true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.goto('/')
  const focusValue = page.getByText('Tu semana', { exact:true }).locator('../..').locator('dd').nth(1)
  await expect(focusValue).not.toHaveText('0m')
  const before = await focusValue.textContent()
  await page.clock.install()
  await page.getByRole('button', { name:'Iniciar reloj',exact:true }).click()
  await expect(page.getByRole('button', { name:'Marcar hoy',exact:true })).toBeVisible()
  await expect(page.getByRole('button', { name:'Pausar',exact:true })).toBeVisible()
  await page.getByRole('button', { name:'Marcar hoy',exact:true }).click()
  await expect(page.getByRole('button', { name:'Hecho hoy',exact:true })).toHaveCount(0)
  await page.clock.fastForward(30_000)
  await page.getByRole('button', { name:'Pausar',exact:true }).click()
  await expect.poll(async () => page.evaluate(() => (() => { const data = JSON.parse(localStorage.getItem('mi-espacio:demo-data:v1')!); const habit = data.projects.find((p: {name:string}) => p.name === 'Estudio de matemáticas'); const task = data.tasks.find((t: {project_id:string}) => t.project_id === habit.id); return data.focusSessions.filter((s: {task_id:string}) => s.task_id === task.id).length })())).toBe(1)
  await page.reload()
  await expect(page.getByRole('button', { name:'Marcar hoy',exact:true })).toBeVisible()
  await page.getByRole('button', { name:'Iniciar reloj',exact:true }).click()
  await expect(page.getByRole('button', { name:'Pausar',exact:true })).toBeVisible()
  await page.clock.fastForward(35_000)
  await expect(page.getByRole('button', { name:'Hecho hoy',exact:true })).toBeVisible()
  await page.getByRole('button', { name:'Pausar',exact:true }).click()
  await expect(focusValue).toHaveText(before!)
  await expect.poll(async () => page.evaluate(() => {
    const data = JSON.parse(localStorage.getItem('mi-espacio:demo-data:v1')!)
    const habit = data.projects.find((p: {name:string}) => p.name === 'Estudio de matemáticas')
    const ids = data.tasks.filter((t: {project_id:string}) => t.project_id === habit.id).map((t: {id:string}) => t.id)
    const rows = data.focusSessions.filter((s: {task_id:string}) => ids.includes(s.task_id))
    return { count:rows.length, seconds:rows[0]?.duration_seconds }
  })).toMatchObject({ count:1,seconds:expect.any(Number) })
  await expect(page.getByText('5 tareas y 4h 10m de enfoque esta semana.', {exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name:'Hecho hoy',exact:true })).toBeVisible()
  await page.goto('/proyectos')
  await page.getByRole('button', { name:'Estudio de matemáticas',exact:true }).click()
  await expect(page.getByRole('region', { name:'Seguimiento de estudio' })).toBeVisible()
  await page.getByLabel('Volumen de trabajo (ejercicios)').fill('12')
  await page.getByRole('button', { name:'Guardar estudio' }).click()
  await expect(page.getByText('Registro guardado', {exact:true})).toBeVisible()
  await page.screenshot({ path:'/tmp/study-panel.png',fullPage:true })
})

test('un Pomodoro completo alcanza la meta y solo se registra una vez', async ({ page }) => {
  await page.goto('/proyectos')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.getByRole('button', { name:'Nuevo proyecto o hábito' }).click()
  await page.getByRole('switch', { name:'Crear como hábito' }).check()
  await page.getByLabel('Tipo de hábito', { exact:true }).selectOption('study')
  await page.getByLabel('Nombre', { exact:true }).fill('Estudio Pomodoro')
  await page.getByLabel('Establecer una meta diaria de tiempo').check()
  await page.getByLabel('Unidad de tiempo', { exact:true }).selectOption('pomodoros')
  await page.getByLabel('Exigir la meta para completar el día').check()
  await page.getByRole('button', { name:'Crear hábito',exact:true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.evaluate(() => {
    const key = 'mi-espacio:demo-data:v1'
    const data = JSON.parse(localStorage.getItem(key)!)
    data.settings.focus_minutes = 1
    localStorage.setItem(key,JSON.stringify(data))
  })
  await page.goto('/')
  await page.reload()
  await page.clock.install()
  await page.getByRole('button', { name:'Iniciar reloj',exact:true }).click()
  await expect(page.getByRole('button', { name:'Marcar hoy',exact:true })).toBeVisible()
  await expect(page.getByRole('button', { name:'Pausar',exact:true })).toBeVisible()
  await page.clock.fastForward(61_000)
  await expect(page.getByRole('button', { name:'Hecho hoy',exact:true })).toBeVisible()
  await expect.poll(async () => page.evaluate(() => {
    const data = JSON.parse(localStorage.getItem('mi-espacio:demo-data:v1')!)
    const habit = data.projects.find((p: {name:string}) => p.name === 'Estudio Pomodoro')
    const task = data.tasks.find((t: {project_id:string}) => t.project_id === habit.id)
    return data.focusSessions.filter((s: {task_id:string;completed:boolean}) => s.task_id === task.id && s.completed).length
  })).toBe(1)
})
